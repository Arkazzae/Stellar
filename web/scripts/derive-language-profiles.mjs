/**
 * Derives the character trigram profiles that
 * `src/stellarr/lib/chatTranslation/detectLanguage.ts` scores chat messages against,
 * from the interface catalogues in `src/stellarr/i18n/messages/`: some 1,700 strings per
 * language, written for this project, Polish and English side by side.
 *
 * Every trigram is taken from folded text (lower case, diacritics removed), so
 * a Polish message typed without ą, ę or ł scores as it would with them. The
 * most frequent trigrams of each language are written out by their log2 count,
 * which is all the detector needs: the rest score as unseen.
 *
 * The output is committed; run this by hand when the catalogues have changed a
 * great deal, and review the difference it makes in the detector's tests:
 *
 *   node scripts/derive-language-profiles.mjs
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const OUTPUT = fileURLToPath(
  new URL("../src/stellarr/lib/chatTranslation/languageProfiles.ts", import.meta.url),
);

/** Trigrams kept per language: enough to tell the two apart and to know either. */
const PROFILE_SIZE = 600;

/** Lower case without diacritics, the way the detector reads a message. */
function fold(text) {
  return text
    .toLowerCase()
    .replace(/ł/g, "l")
    .normalize("NFD")
    .replace(/\p{M}/gu, "");
}

/** Every trigram of the folded words, each word padded with a space on both sides. */
function trigramsOf(text) {
  const counts = new Map();
  for (const word of fold(text).match(/[a-z]+/g) ?? []) {
    const padded = ` ${word} `;
    for (let i = 0; i + 3 <= padded.length; i += 1) {
      const gram = padded.slice(i, i + 3);
      counts.set(gram, (counts.get(gram) ?? 0) + 1);
    }
  }
  return counts;
}

/**
 * The `size` most frequent trigrams, grouped by the integer part of their
 * log2 count, most frequent group first. Ties are broken alphabetically so
 * the same catalogues always give the same file.
 */
export function profileOf(texts, size = PROFILE_SIZE) {
  const counts = new Map();
  for (const text of texts) {
    // Placeholders such as `{name}` are filled in at run time and are no
    // part of the language.
    for (const [gram, count] of trigramsOf(text.replace(/\{[^}]+\}/g, " "))) {
      counts.set(gram, (counts.get(gram) ?? 0) + count);
    }
  }
  const total = [...counts.values()].reduce((sum, count) => sum + count, 0);
  const kept = [...counts]
    .sort(([a, x], [b, y]) => y - x || (a < b ? -1 : 1))
    .slice(0, size);
  const levels = new Map();
  for (const [gram, count] of kept) {
    const level = Math.floor(Math.log2(count));
    levels.set(level, (levels.get(level) ?? "") + gram.replace(/ /g, "_"));
  }
  return {
    total,
    levels: [...levels].sort(([a], [b]) => b - a).map(([level, grams]) => ({ level, grams })),
  };
}

export function render(profiles) {
  const body = Object.entries(profiles)
    .map(([language, { total, levels }]) => {
      const rows = levels
        .map(({ level, grams }) => `      [${level}, "${grams}"],`)
        .join("\n");
      return `  ${language}: {\n    total: ${total},\n    levels: [\n${rows}\n    ],\n  },`;
    })
    .join("\n");
  return `// Generated by scripts/derive-language-profiles.mjs from src/stellarr/i18n/messages/;
// edit that script, not this file.

/**
 * The most frequent character trigrams of folded Polish and English text, as
 * [log2 count, trigrams] rows: three characters each, \`_\` for a word boundary.
 */
export interface TrigramProfile {
  /** Trigrams counted in the source text, seen or not. */
  total: number;
  levels: ReadonlyArray<readonly [level: number, trigrams: string]>;
}

export const PROFILES: Record<"pl" | "en", TrigramProfile> = {
${body}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { pl } = await import("../src/stellarr/i18n/messages/pl.ts");
  const { en } = await import("../src/stellarr/i18n/messages/en.ts");
  const profiles = { pl: profileOf(Object.values(pl)), en: profileOf(Object.values(en)) };
  await writeFile(OUTPUT, render(profiles));
  console.log(`wrote ${OUTPUT}`);
}
