/** The faces the first page needs; every other one is in the pack. */
const UP_FRONT_IDS = new Set(["outfit", "jetbrains-mono"]);

/** The face `theme.css` sets the app in; choosing it is choosing no rule. */
const DEFAULT_ID = "outfit";

const HEADER = "/* Generated by scripts/sync-theme-fonts.mjs. Do not edit by hand. */";

async function fetchOk(url) {
  const response = await fetch(url, { headers: { "user-agent": USER_AGENT } });
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`);
  }
  return response;
}

/** Each @font-face block of a Google Fonts stylesheet with its subset label. */
function readFaces(css) {
  const pairs = css.matchAll(
    /\/\*\s*([^*]+?)\s*\*\/\s*(@font-face\s*\{[\s\S]*?\})/g,
  );
  return [...pairs].map(([, subset, face]) => ({ subset, face }));
}

function indent(text) {
  return text
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
}

async function syncFamily(id, family, query, directory) {
  const url = `https://fonts.googleapis.com/css2?family=${query}&display=swap`;
  const faces = readFaces(await (await fetchOk(url)).text()).filter(
    ({ subset }) => SUBSETS.has(subset),
  );
  if (faces.length === 0) {
    throw new Error(`Google Fonts returned no latin subsets for ${family}`);
  }

  const blocks = [`  /* ${family} */`];
  for (const { subset, face } of faces) {
    const source = /src:\s*url\((https:\/\/[^)]+)\)/.exec(face)?.[1];
    const weight = /font-weight:\s*([^;]+);/.exec(face)?.[1]?.trim();
    if (source === undefined || weight === undefined) {
      throw new Error(`Could not parse ${family} (${subset})`);
    }
    const file = `${id}-${weight.replace(/\s+/g, "-")}-${subset}.woff2`;
    const bytes = Buffer.from(await (await fetchOk(source)).arrayBuffer());
    await writeFile(join(here("../public"), directory, file), bytes);
    blocks.push(
      `  /* ${subset} */`,
      indent(face.replace(source, `/${directory}/${file}`)),
    );
  }
  return blocks;
}

/**
 * The rules that pick a face. Unlayered on purpose: `--font-sans` is
 * declared by Tailwind's `@theme`, which lands in the `theme` layer, and an
 * unlayered rule outranks any layer. The selectors are not anchored to
 * <html>, so an element with `data-font` sets its own subtree in that face.
 */
function typesetRules() {
  const lines = [
    "",
    ":root {",
    "  /* What every stack falls back to, written once. */",
    '  --font-tail: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto,',
    '    "Helvetica Neue", Arial, sans-serif;',
    "}",
  ];
  for (const [id, family, , kind] of FONTS) {
    if (id === DEFAULT_ID) continue;
    const tail = kind === "mono" ? "var(--font-mono)" : "var(--font-tail)";
    lines.push("", `[data-font="${id}"] {`, `  --font-sans: "${family}", ${tail};`, "}");
  }
  return lines;
}

for (const { directory } of [UP_FRONT, PACK]) {
  await mkdir(here(`../public/${directory}`), { recursive: true });
}

const upFront = [HEADER, "@layer base {"];
const pack = [HEADER, "@layer base {"];
for (const [id, family, query] of FONTS) {
  const into = UP_FRONT_IDS.has(id) ? upFront : pack;
  const { directory } = UP_FRONT_IDS.has(id) ? UP_FRONT : PACK;
  into.push(...(await syncFamily(id, family, query, directory)));
}
upFront.push("}", "");
pack.push("}", ...typesetRules(), "");

await writeFile(UP_FRONT.css, upFront.join("\n"));
await writeFile(PACK.css, pack.join("\n"));
console.log(`Synced ${FONTS.length} families into public/fonts and public/typefaces`);
