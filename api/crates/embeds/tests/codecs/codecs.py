"""Ground truth for the character tables and the entity table.

    python3 -I codecs.py expected   > expected.txt      (what the tests read)
    python3 -I codecs.py entities   > entities.txt
    python3 -I codecs.py rust-tables > ../../src/charset/tables.rs
    python3 -I codecs.py rust-entities > ../../src/entity_table.rs

Every table is what Python's own codec says for each of the 256 bytes. A byte
the codec leaves undefined becomes the C1 control of the same value when it
lies in 0x80..0x9F (what Microsoft's tables and every browser do) and U+FFFD
anywhere else.
"""
import codecs
import html.entities
import sys

# Our name -> Python codec name. The names are the ones the Rust side uses.
TABLES = [
    ("windows-1250", "cp1250"),
    ("windows-1251", "cp1251"),
    ("windows-1252", "cp1252"),
    ("windows-1253", "cp1253"),
    ("windows-1254", "cp1254"),
    ("windows-1255", "cp1255"),
    ("windows-1256", "cp1256"),
    ("windows-1257", "cp1257"),
    ("windows-1258", "cp1258"),
    ("iso-8859-2", "iso8859_2"),
    ("iso-8859-4", "iso8859_4"),
    ("iso-8859-5", "iso8859_5"),
    ("iso-8859-6", "iso8859_6"),
    ("iso-8859-7", "iso8859_7"),
    ("iso-8859-8", "iso8859_8"),
    ("iso-8859-13", "iso8859_13"),
    ("iso-8859-15", "iso8859_15"),
    ("koi8-r", "koi8_r"),
    ("koi8-u", "koi8_u"),
]


def table(codec):
    out = []
    for byte in range(256):
        try:
            text = bytes([byte]).decode(codec)
            assert len(text) == 1
            out.append(ord(text))
        except UnicodeDecodeError:
            out.append(byte if 0x80 <= byte <= 0x9F else 0xFFFD)
    return out


def expected():
    for name, codec in TABLES:
        print(name + " " + " ".join("%04X" % c for c in table(codec)))


def entities():
    entries = dict(html.entities.name2codepoint)
    entries["apos"] = 0x27
    for name in sorted(entries):
        print("%s %04X" % (name, entries[name]))


def rust_tables():
    print("// Generated by tests/codecs/codecs.py from Python's codecs. Do not edit.")
    print("// The index of an entry is the byte, the value the code point.")
    print()
    for name, codec in TABLES:
        const = name.upper().replace("-", "_")
        print("pub(super) const %s: [u16; 256] = [" % const)
        values = table(codec)
        for row in range(0, 256, 8):
            print("    " + ", ".join("0x%04X" % v for v in values[row:row + 8]) + ",")
        print("];")
        print()


def rust_entities():
    print("// Generated by tests/codecs/codecs.py from Python's html.entities. Do not edit.")
    print("// The named references of HTML 4 plus `apos`, sorted by name.")
    print()
    entries = dict(html.entities.name2codepoint)
    entries["apos"] = 0x27
    print("pub(crate) const ENTITIES: [(&str, u16); %d] = [" % len(entries))
    for name in sorted(entries):
        assert entries[name] <= 0xFFFF
        print('    ("%s", 0x%04X),' % (name, entries[name]))
    print("];")


if __name__ == "__main__":
    {"expected": expected, "entities": entities, "rust-tables": rust_tables, "rust-entities": rust_entities}[sys.argv[1]]()
