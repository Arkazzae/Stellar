//! Every message the server can say, one name each. The texts live in
//! `english.rs` and `polish.rs`; both match on the key without a fallback arm,
//! so a key that lacks a text in either language does not compile.

/// Declares the key enum and the list of all its values from one list of
/// names, so the two cannot drift apart.
macro_rules! message_keys {
    ($($name:ident,)*) => {
        /// Everything the server says to people.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub enum MessageKey {
            $($name,)*
        }

        impl MessageKey {
            /// Every key, for tests that walk the whole catalogue.
            pub const ALL: &'static [MessageKey] = &[$(MessageKey::$name,)*];
        }
    };
}

