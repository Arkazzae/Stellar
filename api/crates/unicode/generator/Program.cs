// Writes `normalization_tables.rs` from the ICU library of the machine it runs
// on, which has to be the first server's platform: the container image the
// server is shipped in. See the crate's documentation for how it is run.
using System.Runtime.InteropServices;
using System.Text;

static IntPtr Library(out string suffix)
{
    foreach (var folder in new[] { "/usr/lib/aarch64-linux-gnu", "/usr/lib/x86_64-linux-gnu", "/usr/lib" })
    {
        if (!Directory.Exists(folder)) continue;
        foreach (var file in Directory.GetFiles(folder, "libicuuc.so.*").OrderBy(f => f))
        {
            var name = Path.GetFileName(file);
            var parts = name.Split('.');
            if (parts.Length == 3 && int.TryParse(parts[2], out _))
            {
                suffix = "_" + parts[2];
                return NativeLibrary.Load(file);
            }
        }
    }
    throw new InvalidOperationException("no libicuuc found");
}

AppDomain.CurrentDomain.UnhandledException += (_, failure) => { Console.Error.WriteLine(failure.ExceptionObject); Environment.Exit(1); };
var icu = Library(out var suffix);
T Function<T>(string name) where T : Delegate => Marshal.GetDelegateForFunctionPointer<T>(NativeLibrary.GetExport(icu, name + suffix));

var combiningClass = Function<CombiningClass>("u_getCombiningClass");
var versionOf = Function<UnicodeVersion>("u_getUnicodeVersion");
var nfcInstance = Function<Nfc>("unorm2_getNFCInstance");
var rawDecomposition = Function<RawDecomposition>("unorm2_getRawDecomposition");
var composePair = Function<ComposePair>("unorm2_composePair");

int error = 0;
var nfc = nfcInstance(ref error);
if (error > 0) throw new InvalidOperationException($"ICU says {error}");
var version = new byte[4];
versionOf(version);

const int HangulFirst = 0xAC00, HangulLast = 0xD7A3;
var classes = new List<(int First, int Last, int Class)>();
var decompositions = new List<(int From, int First, int Second)>();
var compositions = new List<(int First, int Second, int Composite)>();
var buffer = new ushort[32];
for (var code = 0; code <= 0x10FFFF; code++)
{
    if (code is >= 0xD800 and <= 0xDFFF) continue;
    var cls = combiningClass(code);
    if (cls != 0)
    {
        if (classes.Count > 0 && classes[^1].Class == cls && classes[^1].Last == code - 1)
            classes[^1] = (classes[^1].First, code, cls);
        else
            classes.Add((code, code, cls));
    }
    if (code is >= HangulFirst and <= HangulLast) continue;
    error = 0;
    var length = rawDecomposition(nfc, code, buffer, buffer.Length, ref error);
    if (length < 0 || error > 0) continue;
    var parts = new List<int>();
    var text = new string(buffer.Take(length).Select(unit => (char)unit).ToArray());
    foreach (var rune in text.EnumerateRunes()) parts.Add(rune.Value);
    if (parts.Count is < 1 or > 2) throw new InvalidOperationException($"U+{code:X} decomposes into {parts.Count}");
    var second = parts.Count == 2 ? parts[1] : 0;
    decompositions.Add((code, parts[0], second));
    if (parts.Count == 2 && composePair(nfc, parts[0], parts[1]) == code)
        compositions.Add((parts[0], parts[1], code));
}
compositions.Sort((a, b) => a.First != b.First ? a.First.CompareTo(b.First) : a.Second.CompareTo(b.Second));

var output = new StringBuilder();
output.AppendLine($"//! Generated by `generator/Program.cs` from ICU {suffix[1..]} of the first server's image, which");
output.AppendLine($"//! follows version {version[0]}.{version[1]}.{version[2]} of the Unicode Standard. Do not edit: see the crate's");
output.AppendLine("//! documentation for how to make it again.");
output.AppendLine();
void Table(string name, string type, IEnumerable<string> rows)
{
    output.AppendLine("#[rustfmt::skip]");
    output.AppendLine($"pub(crate) static {name}: &[{type}] = &[");
    var line = new StringBuilder("   ");
    foreach (var row in rows)
    {
        if (line.Length + row.Length + 2 > 100)
        {
            output.AppendLine(line.ToString().TrimEnd());
            line.Clear().Append("   ");
        }
        line.Append(' ').Append(row).Append(',');
    }
    if (line.Length > 3) output.AppendLine(line.ToString());
    output.AppendLine("];");
    output.AppendLine();
}
Table("COMBINING_CLASS", "(u32, u32, u8)", classes.Select(c => $"(0x{c.First:X}, 0x{c.Last:X}, {c.Class})"));
Table("DECOMPOSITION", "(u32, u32, u32)", decompositions.Select(d => $"(0x{d.From:X}, 0x{d.First:X}, 0x{d.Second:X})"));
Table("COMPOSITION", "(u32, u32, u32)", compositions.Select(c => $"(0x{c.First:X}, 0x{c.Second:X}, 0x{c.Composite:X})"));
Console.Out.Write(output.ToString().TrimEnd() + "\n");

delegate byte CombiningClass(int c);
delegate void UnicodeVersion([Out] byte[] version);
delegate IntPtr Nfc(ref int error);
delegate int RawDecomposition(IntPtr norm2, int c, [Out] ushort[] buffer, int capacity, ref int error);
delegate int ComposePair(IntPtr norm2, int a, int b);
