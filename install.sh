#!/usr/bin/env bash
# Stellarr one-click installer.
#
# Checks the host, prepares a Compose directory, writes a .env, and starts the
# container. It is safe to re-run: an existing .env and the data volume are
# preserved, so a second run upgrades the running instance.
#
# From a checkout:
#   ./install.sh
#   ./install.sh --build
#
# Without a checkout (downloads docker-compose.yml and .env.example):
#   curl -fsSL https://raw.githubusercontent.com/Arkazzae/Stellarr/main/install.sh | bash
#
# Unattended:
#   ./install.sh --yes --dir /srv/stellarr --domain chat.example.com --public-ip auto
#
# Written for the bash 3.2 that macOS ships: no associative arrays, no
# mapfile, and empty arrays are expanded with ${name[@]+"${name[@]}"}.
set -euo pipefail

SCRIPT_PATH="${BASH_SOURCE[0]:-}"
SCRIPT_DIR=""
case "$SCRIPT_PATH" in
  ""|bash|sh|-bash|/dev/fd/*|/proc/self/fd/*) ;;
  *)
    if [ -f "$SCRIPT_PATH" ]; then
      SCRIPT_DIR="$(cd "$(dirname "$SCRIPT_PATH")" && pwd -P)"
    fi
    ;;
esac

REPO_SLUG="${STELLARR_REPO_SLUG:-Arkazzae/Stellarr}"
REF="${STELLARR_REF:-main}"
RAW_BASE="https://raw.githubusercontent.com/$REPO_SLUG"
ENV_MARKER="# Generated by Stellarr install.sh. Re-run with --force to refresh managed settings."

INSTALL_DIR="${STELLARR_INSTALL_DIR:-}"
DOMAIN="${STELLARR_DOMAIN:-}"
PUBLIC_IP="${PUBLIC_IP:-}"
HTTPS_PORT="${STELLARR_HTTPS_PORT:-}"
PUBLIC_PORT="${STELLARR_PUBLIC_PORT:-}"
HTTP_PORT="${STELLARR_HTTP_PORT:-}"
MEDIA_PORT="${STELLARR_MEDIA_PORT:-}"
TURN_PORT="${STELLARR_TURN_PORT:-}"
LANGUAGE="${STELLARR_LANGUAGE:-}"
VERSION="${STELLARR_VERSION:-}"

DOMAIN_GIVEN=0
PUBLIC_IP_GIVEN=0
HTTPS_GIVEN=0
PUBLIC_PORT_GIVEN=0
HTTP_GIVEN=0
MEDIA_GIVEN=0
TURN_GIVEN=0
LANGUAGE_GIVEN=0
VERSION_GIVEN=0
[ -n "$DOMAIN" ] && DOMAIN_GIVEN=1
[ -n "$PUBLIC_IP" ] && PUBLIC_IP_GIVEN=1
[ -n "$HTTPS_PORT" ] && HTTPS_GIVEN=1
[ -n "$PUBLIC_PORT" ] && PUBLIC_PORT_GIVEN=1
[ -n "$HTTP_PORT" ] && HTTP_GIVEN=1
[ -n "$MEDIA_PORT" ] && MEDIA_GIVEN=1
[ -n "$TURN_PORT" ] && TURN_GIVEN=1
[ -n "$LANGUAGE" ] && LANGUAGE_GIVEN=1
[ -n "$VERSION" ] && VERSION_GIVEN=1

ASSUME_YES=0
DO_BUILD=0
DO_START=1
INSTALL_DOCKER=0
FORCE=0
FORCE_REMOTE=0
SKIP_PORT_CHECK=0
USE_COLOR=1
MODE=""

C_RESET=""
C_BOLD=""
C_BLUE=""
C_GREEN=""
C_YELLOW=""
C_RED=""

info() { printf '%s==>%s %s\n' "$C_BLUE" "$C_RESET" "$*"; }
ok() { printf '%s  ok%s %s\n' "$C_GREEN" "$C_RESET" "$*"; }
warn() { printf '%swarn%s %s\n' "$C_YELLOW" "$C_RESET" "$*" >&2; }
die() {
  printf '%serr %s %s\n' "$C_RED" "$C_RESET" "$*" >&2
  exit 1
}
have() { command -v "$1" >/dev/null 2>&1; }

usage() {
  cat <<'EOF'
Install a Stellarr instance with Docker Compose.

Usage:
  ./install.sh [options]

Options:
  -d, --dir PATH         Install directory (default: this checkout, or
                         ./stellarr when the script is run on its own)
  -y, --yes              Unattended: accept defaults and never prompt
      --domain NAME      Public hostname or IP (default: localhost)
      --public-ip IP     Public IPv4 for voice from other devices, or "auto"
                         to use the A record of --domain (default: empty)
      --https-port PORT  Host HTTPS port (default: 8443)
      --public-port PORT Public HTTPS port for links, 443 behind a proxy
                         (default: --https-port)
      --http-port PORT   Host HTTP redirect port (default: 8888)
      --media-port PORT  Host UDP port for voice media (default: 49000)
      --turn-port PORT   Host UDP/TCP port for STUN/TURN (default: 3478)
      --language LANG    Interface language, en or pl (default: en)
      --version TAG      Image tag to run (default: latest)
      --ref REF          Git ref used when downloading files (default: main)
      --build            Build the image from this checkout instead of pulling
      --no-start         Prepare and check everything, but do not start
      --install-docker   Install Docker Engine with get.docker.com if missing
      --force            Refresh docker-compose.yml and re-apply installer
                         settings to an existing .env (keeps .env.bak)
      --skip-port-check  Skip the host port availability check
      --remote           Download docker-compose.yml even from a checkout
      --no-color         Disable colored output
  -h, --help             Show this help message

Environment:
  STELLARR_INSTALL_DIR, STELLARR_DOMAIN, PUBLIC_IP, STELLARR_HTTPS_PORT,
  STELLARR_PUBLIC_PORT, STELLARR_HTTP_PORT, STELLARR_MEDIA_PORT, STELLARR_TURN_PORT,
  STELLARR_LANGUAGE, STELLARR_VERSION, STELLARR_REF and STELLARR_REPO_SLUG
  set the defaults of the options above.

After installation:
  docker compose logs stellarr | grep "Setup code"
  Open the HTTPS address and create the owner account at /setup.
EOF
}

need_value() {
  if [ "$#" -lt 2 ] || [ -z "$2" ]; then
    die "Option $1 requires a value"
  fi
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    -d|--dir)
      need_value "$@"
      INSTALL_DIR="$2"
      shift 2
      ;;
    -y|--yes)
      ASSUME_YES=1
      shift
      ;;
    --domain)
      need_value "$@"
      DOMAIN="$2"
      DOMAIN_GIVEN=1
      shift 2
      ;;
    --public-ip)
      need_value "$@"
      PUBLIC_IP="$2"
      PUBLIC_IP_GIVEN=1
      shift 2
      ;;
    --https-port)
      need_value "$@"
      HTTPS_PORT="$2"
      HTTPS_GIVEN=1
      shift 2
      ;;
    --public-port)
      need_value "$@"
      PUBLIC_PORT="$2"
      PUBLIC_PORT_GIVEN=1
      shift 2
      ;;
    --http-port)
      need_value "$@"
      HTTP_PORT="$2"
      HTTP_GIVEN=1
      shift 2
      ;;
    --media-port)
      need_value "$@"
      MEDIA_PORT="$2"
      MEDIA_GIVEN=1
      shift 2
      ;;
    --turn-port)
      need_value "$@"
      TURN_PORT="$2"
      TURN_GIVEN=1
      shift 2
      ;;
    --language)
      need_value "$@"
      LANGUAGE="$2"
      LANGUAGE_GIVEN=1
      shift 2
      ;;
    --version)
      need_value "$@"
      VERSION="$2"
      VERSION_GIVEN=1
      shift 2
      ;;
    --ref)
      need_value "$@"
      REF="$2"
      shift 2
      ;;
    --build)
      DO_BUILD=1
      shift
      ;;
    --no-start)
      DO_START=0
      shift
      ;;
    --install-docker)
      INSTALL_DOCKER=1
      shift
      ;;
    --force)
      FORCE=1
      shift
      ;;
    --skip-port-check)
      SKIP_PORT_CHECK=1
      shift
      ;;
    --remote)
      FORCE_REMOTE=1
      shift
      ;;
    --no-color)
      USE_COLOR=0
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "Unknown option: $1 (try --help)"
      ;;
  esac
done

if [ "$USE_COLOR" -eq 1 ] && [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  C_RESET=$'\033[0m'
  C_BOLD=$'\033[1m'
  C_BLUE=$'\033[34m'
  C_GREEN=$'\033[32m'
  C_YELLOW=$'\033[33m'
  C_RED=$'\033[31m'
fi

# A checkout next to the script installs in place; a downloaded script sets up
# a fresh directory. --remote forces the download path.
if [ "$FORCE_REMOTE" -eq 0 ] && [ -n "$SCRIPT_DIR" ] && [ -f "$SCRIPT_DIR/docker-compose.yml" ]; then
  MODE=local
else
  MODE=remote
fi

if [ -z "$INSTALL_DIR" ]; then
  if [ "$MODE" = local ]; then
    INSTALL_DIR="$SCRIPT_DIR"
  else
    INSTALL_DIR="$PWD/stellarr"
  fi
fi

if [ "$ASSUME_YES" -eq 1 ] || [ ! -r /dev/tty ]; then
  INTERACTIVE=0
else
  INTERACTIVE=1
fi

ask() {
  local prompt="$1"
  local default="$2"
  local answer=""
  if [ "$INTERACTIVE" -ne 1 ]; then
    printf '%s' "$default"
    return 0
  fi
  if [ -n "$default" ]; then
    printf '%s [%s]: ' "$prompt" "$default" >/dev/tty
  else
    printf '%s: ' "$prompt" >/dev/tty
  fi
  IFS= read -r answer < /dev/tty || answer=""
  if [ -z "$answer" ]; then
    answer="$default"
  fi
  printf '%s' "$answer"
}

ask_yes_no() {
  local prompt="$1"
  local default="$2"
  local answer=""
  if [ "$INTERACTIVE" -ne 1 ]; then
    [ "$default" = "y" ]
    return
  fi
  printf '%s [%s]: ' "$prompt" "$default" >/dev/tty
  IFS= read -r answer < /dev/tty || answer=""
  if [ -z "$answer" ]; then
    answer="$default"
  fi
  case "$answer" in
    y|Y|yes|YES) return 0 ;;
    *) return 1 ;;
  esac
}

valid_port() {
  case "$1" in
    ""|*[!0-9]*) return 1 ;;
  esac
  [ "$1" -ge 1 ] && [ "$1" -le 65535 ]
}

normalize_domain() {
  local value="$1"
  value="${value#http://}"
  value="${value#https://}"
  value="${value%%/*}"
  case "$value" in
    \[*\]:*) value="${value%:*}" ;;
    *:*:*) ;;
    *:*) value="${value%%:*}" ;;
  esac
  printf '%s' "$value"
}

install_docker_engine() {
  local script_file
  if [ "$OS" = "Darwin" ]; then
    die "Install Docker Desktop for Mac from https://docs.docker.com/desktop/ and re-run this script."
  fi
  info "Installing Docker Engine from https://get.docker.com"
  script_file="$(mktemp "${TMPDIR:-/tmp}/stellarr-docker-install.XXXXXX")"
  if ! fetch "https://get.docker.com" "$script_file"; then
    rm -f "$script_file"
    die "Could not download the Docker installation script."
  fi
  if [ "$(id -u)" -eq 0 ]; then
    sh "$script_file" || { rm -f "$script_file"; die "Docker installation failed."; }
  else
    if [ "$INTERACTIVE" -eq 1 ]; then
      sudo sh "$script_file" || { rm -f "$script_file"; die "Docker installation failed."; }
    else
      sudo -n sh "$script_file" || { rm -f "$script_file"; die "Docker installation failed. Re-run with root or --install-docker interactively."; }
    fi
  fi
  rm -f "$script_file"
  if have systemctl; then
    if [ "$(id -u)" -eq 0 ]; then
      systemctl enable --now docker >/dev/null 2>&1 || true
    else
      sudo systemctl enable --now docker >/dev/null 2>&1 || true
    fi
  fi
  if [ "$(id -u)" -ne 0 ] && have usermod; then
    sudo usermod -aG docker "$(id -un)" >/dev/null 2>&1 || true
  fi
  if ! docker info >/dev/null 2>&1 && [ "$(id -u)" -ne 0 ]; then
    warn "Docker was installed. Your user may need to log out and back in for the docker group; this run will use sudo."
  fi
}

fetch() {
  local url="$1"
  local dest="$2"
  if have curl; then
    curl -fsSL --retry 3 --connect-timeout 20 "$url" -o "$dest"
  elif have wget; then
    wget -qO "$dest" "$url"
  else
    return 1
  fi
}

set_env() {
  local key="$1"
  local value="$2"
  local file="$3"
  local tmp="$file.tmp.$$"
  grep -v "^${key}=" "$file" > "$tmp" || true
  printf '%s=%s\n' "$key" "$value" >> "$tmp"
  mv "$tmp" "$file"
}

read_env() {
  local key="$1"
  local file="$2"
  sed -n "s/^${key}=//p" "$file" | tail -n 1
}

port_tool=""
if have ss; then
  port_tool=ss
elif have lsof; then
  port_tool=lsof
elif have netstat; then
  port_tool=netstat
fi

port_in_use() {
  local proto="$1"
  local port="$2"
  case "$port_tool" in
    ss)
      if [ "$proto" = udp ]; then
        ss -H -lun 2>/dev/null | awk '{print $4}' | grep -Eq "[:.]${port}$"
      else
        ss -H -ltn 2>/dev/null | awk '{print $4}' | grep -Eq "[:.]${port}$"
      fi
      ;;
    lsof)
      if [ "$proto" = udp ]; then
        lsof -nP -iUDP:"$port" >/dev/null 2>&1
      else
        lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1
      fi
      ;;
    netstat)
      if [ "$proto" = udp ]; then
        netstat -lnu 2>/dev/null | awk '{print $4}' | grep -Eq "[:.]${port}$"
      else
        netstat -lnt 2>/dev/null | awk '{print $4}' | grep -Eq "[:.]${port}$"
      fi
      ;;
    *)
      return 1
      ;;
  esac
}

# --- Wizard ----------------------------------------------------------------

PRELOADED_ENV=0
if [ -f "$INSTALL_DIR/.env" ] && grep -qF "$ENV_MARKER" "$INSTALL_DIR/.env"; then
  PRELOADED_ENV=1
  [ -n "$DOMAIN" ] || DOMAIN="$(read_env STELLARR_DOMAIN "$INSTALL_DIR/.env")"
  [ -n "$PUBLIC_IP" ] || PUBLIC_IP="$(read_env PUBLIC_IP "$INSTALL_DIR/.env")"
  [ -n "$HTTPS_PORT" ] || HTTPS_PORT="$(read_env STELLARR_HTTPS_PORT "$INSTALL_DIR/.env")"
  [ -n "$PUBLIC_PORT" ] || PUBLIC_PORT="$(read_env STELLARR_PUBLIC_PORT "$INSTALL_DIR/.env")"
  [ -n "$HTTP_PORT" ] || HTTP_PORT="$(read_env STELLARR_HTTP_PORT "$INSTALL_DIR/.env")"
  [ -n "$MEDIA_PORT" ] || MEDIA_PORT="$(read_env STELLARR_MEDIA_PORT "$INSTALL_DIR/.env")"
  [ -n "$TURN_PORT" ] || TURN_PORT="$(read_env STELLARR_TURN_PORT "$INSTALL_DIR/.env")"
  [ -n "$LANGUAGE" ] || LANGUAGE="$(read_env STELLARR_LANGUAGE "$INSTALL_DIR/.env")"
  [ -n "$VERSION" ] || VERSION="$(read_env STELLARR_VERSION "$INSTALL_DIR/.env")"
fi

if [ "$INTERACTIVE" -eq 1 ]; then
  printf '\n%sStellarr installer%s\n' "$C_BOLD" "$C_RESET"
  printf 'Install directory: %s\n' "$INSTALL_DIR"
  if [ "$PRELOADED_ENV" -eq 1 ]; then
    printf 'Existing installation: reusing settings from .env\n'
  fi
  printf '\n'
fi

if [ "$PRELOADED_ENV" -eq 0 ]; then
  if [ -z "$DOMAIN" ]; then
    DOMAIN="$(ask 'Public hostname or IP (localhost = only this machine)' 'localhost')"
  fi
  if [ -z "$PUBLIC_IP" ] && [ "$INTERACTIVE" -eq 1 ]; then
    PUBLIC_IP="$(ask 'Public IPv4 for voice from other devices (leave empty for local only)' '')"
  fi

  if [ -z "$HTTPS_PORT" ] && [ -z "$HTTP_PORT" ] && [ -z "$MEDIA_PORT" ] && [ -z "$TURN_PORT" ]; then
    if [ "$INTERACTIVE" -eq 1 ]; then
      if ! ask_yes_no 'Use default ports (HTTPS 8443, HTTP 8888, media 49000, TURN 3478)?' 'y'; then
        HTTPS_PORT="$(ask 'HTTPS port' '8443')"
        HTTP_PORT="$(ask 'HTTP redirect port' '8888')"
        MEDIA_PORT="$(ask 'Voice media UDP port' '49000')"
        TURN_PORT="$(ask 'STUN/TURN port' '3478')"
      fi
    fi
  fi

  if [ -z "$LANGUAGE" ]; then
    LANGUAGE="$(ask 'Interface language (en or pl)' 'en')"
  fi

  if [ -z "$VERSION" ]; then
    VERSION="$(ask 'Image tag' 'latest')"
  fi
fi

DOMAIN="$(normalize_domain "$DOMAIN")"
[ -n "$DOMAIN" ] || die "The domain cannot be empty. Use localhost for a local test."

HTTPS_PORT="${HTTPS_PORT:-8443}"
PUBLIC_PORT="${PUBLIC_PORT:-$HTTPS_PORT}"
HTTP_PORT="${HTTP_PORT:-8888}"
MEDIA_PORT="${MEDIA_PORT:-49000}"
TURN_PORT="${TURN_PORT:-3478}"
LANGUAGE="${LANGUAGE:-en}"
VERSION="${VERSION:-latest}"

valid_port "$HTTPS_PORT" || die "Invalid HTTPS port: $HTTPS_PORT"
valid_port "$PUBLIC_PORT" || die "Invalid public HTTPS port: $PUBLIC_PORT"
valid_port "$HTTP_PORT" || die "Invalid HTTP port: $HTTP_PORT"
valid_port "$MEDIA_PORT" || die "Invalid media port: $MEDIA_PORT"
valid_port "$TURN_PORT" || die "Invalid TURN port: $TURN_PORT"

case "$LANGUAGE" in
  en|pl) ;;
  *) die "Unsupported language: $LANGUAGE (use en or pl)" ;;
esac

case "$VERSION" in
  ""|*[!A-Za-z0-9._-]*) die "Invalid image tag: $VERSION" ;;
esac

case "$REF" in
  ""|*[!A-Za-z0-9._/-]*) die "Invalid git ref: $REF" ;;
esac

SETTINGS_EXPLICIT=0
for flag in "$DOMAIN_GIVEN" "$PUBLIC_IP_GIVEN" "$HTTPS_GIVEN" "$PUBLIC_PORT_GIVEN" \
  "$HTTP_GIVEN" "$MEDIA_GIVEN" "$TURN_GIVEN" "$LANGUAGE_GIVEN" "$VERSION_GIVEN"; do
  if [ "$flag" -eq 1 ]; then
    SETTINGS_EXPLICIT=1
  fi
done

# --- Host checks -----------------------------------------------------------

OS="$(uname -s 2>/dev/null || printf unknown)"
ARCH="$(uname -m 2>/dev/null || printf unknown)"
info "Host: $OS $ARCH"

case "$ARCH" in
  x86_64|amd64|aarch64|arm64) ;;
  *) warn "Stellarr publishes images for amd64 and arm64 only; $ARCH may fail to run." ;;
esac

case "$OS" in
  Linux|Darwin) ;;
  *) warn "This installer was written for Linux and macOS; continuing anyway." ;;
esac

mkdir -p "$INSTALL_DIR" || die "Cannot create $INSTALL_DIR"
cd "$INSTALL_DIR" || die "Cannot enter $INSTALL_DIR"
INSTALL_DIR="$(pwd -P)"

if [ ! -w "$INSTALL_DIR" ]; then
  die "$INSTALL_DIR is not writable. Run with a user that can write there or pass --dir."
fi

if [ -r /proc/meminfo ]; then
  mem_kb="$(awk '/^MemTotal:/ {print $2}' /proc/meminfo 2>/dev/null || printf 0)"
  if [ "${mem_kb:-0}" -lt 2097152 ]; then
    warn "Less than 2 GiB of RAM detected; the default container memory cap is 4 GiB."
  fi
fi

avail_kb="$(df -Pk "$INSTALL_DIR" 2>/dev/null | awk 'NR==2 {print $4}' || printf 0)"
if [ "${avail_kb:-0}" -lt 2097152 ]; then
  warn "Less than 2 GiB free in $INSTALL_DIR. The image needs about 400 MiB plus the data volume."
fi

if [ "$MODE" = remote ]; then
  if ! have curl && ! have wget; then
    die "curl or wget is required to download docker-compose.yml and .env.example."
  fi
fi

if ! have docker; then
  if [ "$INSTALL_DOCKER" -eq 1 ]; then
    install_docker_engine
  elif [ "$INTERACTIVE" -eq 1 ] && ask_yes_no 'Docker is not installed. Install Docker Engine now (requires sudo)?' 'y'; then
    install_docker_engine
  else
    die "Docker is not installed. See https://docs.docker.com/engine/install/ or re-run with --install-docker."
  fi
fi

DOCKER="docker"
if ! docker info >/dev/null 2>&1; then
  if [ "$(id -u)" -ne 0 ] && have sudo; then
    if [ "$INTERACTIVE" -eq 1 ]; then
      if sudo -v >/dev/null 2>&1 && sudo docker info >/dev/null 2>&1; then
        DOCKER="sudo docker"
      fi
    elif sudo -n docker info >/dev/null 2>&1; then
      DOCKER="sudo docker"
    fi
  fi
fi

if ! $DOCKER info >/dev/null 2>&1 && [ "$OS" = "Linux" ] && have systemctl; then
  if [ "$(id -u)" -eq 0 ]; then
    systemctl start docker >/dev/null 2>&1 || true
  elif [ "$INTERACTIVE" -eq 1 ]; then
    sudo systemctl start docker >/dev/null 2>&1 || true
  fi
fi

if ! $DOCKER info >/dev/null 2>&1; then
  die "The Docker daemon is not reachable. Start Docker (systemctl start docker) and check that your user can run 'docker info'."
fi

COMPOSE="$DOCKER compose"
if ! $COMPOSE version >/dev/null 2>&1; then
  if [ "$DOCKER" = "docker" ] && have docker-compose && docker-compose version >/dev/null 2>&1; then
    COMPOSE="docker-compose"
    warn "Using standalone docker-compose; the Docker Compose plugin is recommended."
  else
    die "The Docker Compose plugin is missing. Install docker-compose-plugin for your distribution."
  fi
fi
ok "Docker and Compose are available"

# --- Files -----------------------------------------------------------------

if [ "$MODE" = remote ] && [ "$DO_BUILD" -eq 1 ]; then
  die "Building from source needs the checkout. Clone the repository and run ./install.sh --build there."
fi

if [ "$MODE" = remote ]; then
  if [ -f docker-compose.yml ] && [ "$FORCE" -eq 0 ]; then
    ok "Keeping existing docker-compose.yml"
  else
    info "Downloading docker-compose.yml from $REPO_SLUG@$REF"
    compose_tmp="$(mktemp "${TMPDIR:-/tmp}/stellarr-compose.XXXXXX")"
    if ! fetch "$RAW_BASE/$REF/docker-compose.yml" "$compose_tmp"; then
      rm -f "$compose_tmp"
      die "Could not download docker-compose.yml from $RAW_BASE/$REF/docker-compose.yml"
    fi
    if ! grep -q '^name: stellarr' "$compose_tmp"; then
      rm -f "$compose_tmp"
      die "The downloaded docker-compose.yml does not look like Stellarr's."
    fi
    if [ -f docker-compose.yml ]; then
      cp docker-compose.yml docker-compose.yml.bak
    fi
    mv "$compose_tmp" docker-compose.yml
    chmod 644 docker-compose.yml 2>/dev/null || true
    ok "Saved docker-compose.yml"
  fi
else
  if [ "$INSTALL_DIR" = "$SCRIPT_DIR" ]; then
    ok "Using the checkout at $INSTALL_DIR"
  else
    if [ "$DO_BUILD" -eq 1 ]; then
      die "Building from source needs the whole checkout. Run ./install.sh in the checkout or point --dir at it."
    fi
    if [ ! -f docker-compose.yml ] || [ "$FORCE" -eq 1 ]; then
      cp "$SCRIPT_DIR/docker-compose.yml" docker-compose.yml
      ok "Copied docker-compose.yml"
    else
      ok "Keeping existing docker-compose.yml"
    fi
    if [ ! -f .env.example ] && [ -f "$SCRIPT_DIR/.env.example" ]; then
      cp "$SCRIPT_DIR/.env.example" .env.example
    fi
  fi
fi

ENV_EXISTED=0
ENV_FOREIGN=0

if [ "$MODE" = remote ] && [ ! -f .env.example ]; then
  info "Downloading .env.example"
  fetch "$RAW_BASE/$REF/.env.example" .env.example || true
fi

if [ ! -f .env ]; then
  :
elif ! grep -qF "$ENV_MARKER" .env; then
  # A .env from a development checkout or a hand-written file: never adopt it
  # silently, because it can carry COMPOSE_PROJECT_NAME or dev-only settings.
  ENV_EXISTED=1
  ENV_FOREIGN=1
else
  ENV_EXISTED=1
fi

if [ "$ENV_FOREIGN" -eq 1 ] && [ "$FORCE" -eq 0 ]; then
  if [ "$INTERACTIVE" -eq 1 ]; then
    if ! ask_yes_no "Existing .env was not created by install.sh. Back it up and generate a fresh one?" 'y'; then
      die "Installation cancelled. Move .env away, or re-run with --force to back it up and regenerate."
    fi
  else
    warn "Existing .env was not created by install.sh; backing it up and generating a fresh one."
  fi
  FORCE=1
fi

if [ "$ENV_EXISTED" -eq 0 ] || [ "$FORCE" -eq 1 ]; then
  if [ "$ENV_EXISTED" -eq 1 ]; then
    cp .env .env.bak
    ok "Backed up the previous .env to .env.bak"
  fi
  if [ -f .env.example ]; then
    {
      printf '%s\n' "$ENV_MARKER"
      cat .env.example
    } > .env
  else
    {
      printf '%s\n' "$ENV_MARKER"
      printf '# See https://github.com/%s/blob/%s/.env.example\n' "$REPO_SLUG" "$REF"
    } > .env
  fi
  set_env STELLARR_DOMAIN "$DOMAIN" .env
  set_env STELLARR_PUBLIC_PORT "$PUBLIC_PORT" .env
  set_env PUBLIC_IP "$PUBLIC_IP" .env
  set_env STELLARR_HTTPS_PORT "$HTTPS_PORT" .env
  set_env STELLARR_HTTP_PORT "$HTTP_PORT" .env
  set_env STELLARR_MEDIA_PORT "$MEDIA_PORT" .env
  set_env STELLARR_TURN_PORT "$TURN_PORT" .env
  set_env STELLARR_LANGUAGE "$LANGUAGE" .env
  set_env STELLARR_VERSION "$VERSION" .env
  chmod 600 .env 2>/dev/null || true
  ok "Wrote $INSTALL_DIR/.env"
elif [ "$SETTINGS_EXPLICIT" -eq 1 ]; then
  if [ "$DOMAIN_GIVEN" -eq 1 ]; then
    set_env STELLARR_DOMAIN "$DOMAIN" .env
  fi
  if [ "$PUBLIC_IP_GIVEN" -eq 1 ]; then
    set_env PUBLIC_IP "$PUBLIC_IP" .env
  fi
  if [ "$HTTPS_GIVEN" -eq 1 ]; then
    set_env STELLARR_HTTPS_PORT "$HTTPS_PORT" .env
  fi
  if [ "$HTTPS_GIVEN" -eq 1 ] || [ "$PUBLIC_PORT_GIVEN" -eq 1 ]; then
    set_env STELLARR_PUBLIC_PORT "$PUBLIC_PORT" .env
  fi
  if [ "$HTTP_GIVEN" -eq 1 ]; then
    set_env STELLARR_HTTP_PORT "$HTTP_PORT" .env
