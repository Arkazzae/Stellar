if [ "$DO_START" -eq 0 ]; then
  info "Files are ready in $INSTALL_DIR"
  printf '\nStart the instance with:\n  cd %s && %s up -d\n\n' "$INSTALL_DIR" "$COMPOSE"
  exit 0
fi

info "Validating the Compose configuration"
$COMPOSE config -q || die "docker compose config failed; check $INSTALL_DIR/.env"

if [ "$DO_BUILD" -eq 1 ]; then
  info "Building and starting the image (this can take several minutes)"
  $COMPOSE up -d --build || die "docker compose up failed"
else
  image="ghcr.io/arkazzae/stellarr:$VERSION"
  info "Pulling $image"
  if ! $COMPOSE pull; then
    warn "Image pull failed."
    if ! $DOCKER image inspect "$image" >/dev/null 2>&1; then
      die "No local copy of $image either. Check network/GHCR access, or run ./install.sh --build in a checkout."
    fi
    warn "Using the local copy of $image"
  fi
  $COMPOSE up -d || die "docker compose up failed"
fi

info "Waiting for the container to become healthy"
elapsed=0
healthy=0
while [ "$elapsed" -lt 180 ]; do
  status="$($DOCKER inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' stellarr 2>/dev/null || true)"
  case "$status" in
    healthy|running)
      healthy=1
      break
      ;;
    unhealthy|exited|dead)
      break
      ;;
  esac
  sleep 3
  elapsed=$((elapsed + 3))
done

if [ "$healthy" -ne 1 ]; then
  warn "The container did not become healthy within 180 seconds."
  $COMPOSE ps || true
  $DOCKER logs --tail=80 stellarr 2>&1 | tail -n 80 || true
  die "Startup failed. Inspect the logs above, then run: cd $INSTALL_DIR && $COMPOSE logs"
fi

ok "Container is $status"

if [ "$PUBLIC_PORT" = "443" ]; then
  WEB_URL="https://$DOMAIN"
else
  WEB_URL="https://$DOMAIN:$PUBLIC_PORT"
fi

setup_code=""
setup_line="$($DOCKER logs stellarr 2>&1 | grep -i 'Setup code' | tail -n 1 || true)"
if [ -n "$setup_line" ]; then
  setup_code="$(printf '%s\n' "$setup_line" \
    | sed -n 's/.*[Ss]etup code:[[:space:]]*//p' \
    | awk '{print $1}' \
    | sed 's/[.,;]$//')"
fi

# A stale code remains in the log after the owner account exists. Ask the API
# whether the instance still needs one, when curl is available.
setup_required=""
if have curl; then
  if [ "$HTTPS_PORT" = "443" ]; then
    registration_url="https://127.0.0.1/api/auth/registration"
  else
    registration_url="https://127.0.0.1:$HTTPS_PORT/api/auth/registration"
  fi
  registration_json="$(curl -kfsS --max-time 10 "$registration_url" 2>/dev/null || true)"
  if printf '%s' "$registration_json" | grep -Eq '"setupRequired"[[:space:]]*:[[:space:]]*false'; then
    setup_required=0
  elif printf '%s' "$registration_json" | grep -Eq '"setupRequired"[[:space:]]*:[[:space:]]*true'; then
    setup_required=1
  fi
fi

printf '\n%sStellarr is running.%s\n\n' "$C_BOLD$C_GREEN" "$C_RESET"
printf '  Web client:  %s\n' "$WEB_URL"
printf '  Setup page:  %s/setup\n' "$WEB_URL"
printf '  Cockpit:     %s/cockpit\n' "$WEB_URL"
printf '  Install dir: %s\n' "$INSTALL_DIR"
if [ "$setup_required" = "0" ]; then
  printf '\n  The instance already has an owner account; sign in normally.\n'
elif [ -n "$setup_code" ]; then
  printf '\n  Setup code:  %s\n' "$setup_code"
  printf '  Use it once at %s/setup to create the owner account.\n' "$WEB_URL"
else
  printf '\n  No setup code found. If this is an existing instance, sign in normally;\n'
  printf '  otherwise check: cd %s && %s logs stellarr | grep "Setup code"\n' "$INSTALL_DIR" "$COMPOSE"
fi

if [ "$DOMAIN" = "localhost" ] || [ "$DOMAIN" = "127.0.0.1" ]; then
  printf '\n  The certificate is self-signed; accept the browser warning.\n'
fi
