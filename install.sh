# --- Ports -----------------------------------------------------------------

if [ "$SKIP_PORT_CHECK" -eq 0 ]; then
  container_running=0
  if $DOCKER inspect -f '{{.State.Running}}' stellarr >/dev/null 2>&1; then
    container_running=1
  fi
  if [ "$container_running" -eq 1 ]; then
    ok "Existing stellarr container is running; skipping the host port check"
  elif [ -z "$port_tool" ]; then
    warn "No ss, lsof or netstat found; skipping the host port check"
  else
    conflicts=""
    for spec in "tcp:$HTTPS_PORT:HTTPS" "tcp:$HTTP_PORT:HTTP" "tcp:$TURN_PORT:TURN" "udp:$TURN_PORT:TURN" "udp:$MEDIA_PORT:Media"; do
      proto="${spec%%:*}"
      rest="${spec#*:}"
      port="${rest%%:*}"
      label="${rest#*:}"
      if port_in_use "$proto" "$port"; then
        conflicts="${conflicts}  - $label: $proto/$port
"
      fi
    done
    port=49160
    while [ "$port" -le 49200 ]; do
      if port_in_use udp "$port"; then
        conflicts="${conflicts}  - TURN relay range: udp/$port
"
        break
      fi
      port=$((port + 1))
    done
    if [ -n "$conflicts" ]; then
      printf 'Ports already in use:\n%s' "$conflicts" >&2
      die "Free these ports or re-run with --https-port/--http-port/--media-port/--turn-port."
    fi
    ok "Required ports are free"
  fi
else
  warn "Skipping the host port check (--skip-port-check)"
fi

